"""Generate deterministic tool/schema reference without contacting any appliance."""
import argparse
import asyncio
import json
from pathlib import Path
import tempfile
from firewalla_mcp.models import Config
from firewalla_mcp.server import build_server

async def render():
    with tempfile.TemporaryDirectory() as d:
        ledger=Path(d)/'ledger';ledger.mkdir(mode=0o700)
        base=dict(sites={},approval_consumed_directory=str(ledger),audit_file=str(Path(d)/'audit'),vpn_target_policy='approval_bound',vpn_confirmation_mode='host_confirmed',write_confirmation_mode='host_confirmed')
        modes={
            'read':(Config(**base),dict(readonly_catalog=True)),
            'vpn':(Config(**base,vpn_writes_enabled=True),dict(vpn_write_catalog=True)),
            'vpn+capture':(Config(**base,vpn_writes_enabled=True,capture_enabled=True),dict(vpn_write_catalog=True)),
            'combined+capture':(Config(**base,vpn_writes_enabled=True,writes_enabled=True,capture_enabled=True),{}),
        }
        catalog={};counts={}
        for mode,(config,kwargs) in modes.items():
            tools=await build_server(config,**kwargs).list_tools();counts[mode]=len(tools)
            for tool in tools:
                row=catalog.setdefault(tool.name,{'tool':tool,'modes':[]});row['modes'].append(mode)
        lines=['# Generated MCP tool reference','', 'Generated by `python scripts/generate_catalog.py`; no appliance calls. Catalog presence is not live availability. See [support/evidence matrix](features.md) and [write safety](writes.md).','', 'Modes: '+', '.join(f'`{m}` {n}' for m,n in counts.items())+'.', '', 'All router operations use internal verified SSH. Read tools may expose private metadata; DNS/TCP tools generate traffic. Import preview writes a router-local journal. Capture and apply require explicit host confirmation. See each description for outputs, bounds and side effects. Existing sudo is required for kernel operations/capture and selected diagnostics; no privilege is granted by tool registration.', '']
        for name,row in sorted(catalog.items()):
            t=row['tool'];ann=t.annotations.model_dump(exclude_none=True) if t.annotations else {}
            lines += ['## `'+name+'`','', 'Catalogs: '+', '.join('`'+x+'`' for x in row['modes'])+'.','', ' '.join((t.description or '').split()),'', 'Annotations: `'+json.dumps(ann,sort_keys=True)+'`','', '```json',json.dumps(t.inputSchema,indent=2,sort_keys=True),'```','']
        return '\n'.join(lines)
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();path=Path(__file__).resolve().parents[1]/'docs/tool-reference.md';content=asyncio.run(render())
    if args.check:
        if not path.exists() or path.read_text()!=content:raise SystemExit('Tool reference is stale; run scripts/generate_catalog.py')
    else:path.write_text(content)
